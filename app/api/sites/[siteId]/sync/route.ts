import { after } from "next/server"
import { requireAuth } from "@/lib/auth"
import { createAdminClient } from "@/lib/supabase/admin"
import { successResponse, errors } from "@/lib/api/response"
import { syncSite, isSyncInProgress } from "@/lib/sync/gsc-sync"
import { checkAccess, sitesWithinPlan } from "@/lib/billing/access"
import { generateRecommendations } from "@/lib/ai/generate-recommendations"
import { autoGeneratedRecently } from "@/lib/recommendations/quota"
import { isUuid } from "@/lib/api/validate"

/** Search Console only updates daily; re-syncing more often just burns quota. */
const SYNC_COOLDOWN_MS = 15 * 60 * 1000

export const maxDuration = 300 // 5 minutes max for sync

export async function POST(
  _request: Request,
  { params }: { params: Promise<{ siteId: string }> }
) {
  try {
    const user = await requireAuth()
    const { siteId } = await params
    if (!isUuid(siteId)) return errors.notFound("Site")
    const admin = createAdminClient()

    if (!checkAccess(user).hasAccess) return errors.trialExpired()

    // Verify ownership
    const { data: site, error: fetchError } = await admin
      .from("sites")
      .select("*")
      .eq("id", siteId)
      .eq("user_id", user.id)
      .single()

    if (fetchError || !site) return errors.notFound("Site")

    if (isSyncInProgress(site.sync_status, site.sync_started_at)) {
      return errors.validation("Sync is already in progress")
    }

    if (
      site.sync_status === "completed" &&
      site.last_synced_at &&
      Date.now() - new Date(site.last_synced_at).getTime() < SYNC_COOLDOWN_MS
    ) {
      return errors.validation("This site synced a few minutes ago. Search Console only updates once a day.")
    }

    // After a downgrade, sites beyond the plan's limit stop syncing.
    const { data: userSites } = await admin.from("sites").select("id, created_at").eq("user_id", user.id)
    if (!sitesWithinPlan(user, userSites ?? []).some((s) => s.id === siteId)) {
      return errors.planLimit("This site is beyond your plan's site limit. Upgrade or remove a site to sync it.")
    }

    // Use next/server after() to keep the function alive after responding
    after(async () => {
      try {
        // Stay well inside the 300s function limit; a long backfill resumes
        // on the next sync from the newest stored day.
        await syncSite(siteId, { timeBudgetMs: 200_000 })
      } catch (err) {
        console.error(`Background sync failed for site ${siteId}:`, err)
        return
      }

      // Note: syncSite() now refreshes the striking-distance materialized view
      // before flipping sync_status to "completed", so clients polling status
      // don't race against a stale view. Auto-rec generation stays here because
      // it's slower and fine to run after status=completed.

      // Post-sync: auto-generate recommendations for first-time users
      // so they land on the dashboard with something to act on immediately.
      // Gated on "zero non-expired recs" so repeat syncs don't re-bill the AI
      // call, and at most once a day per site, so "delete recs, sync again"
      // isn't a free AI run.
      try {
        const { count } = await admin
          .from("recommendations")
          .select("*", { count: "exact", head: true })
          .eq("site_id", siteId)
          .gt("expires_at", new Date().toISOString())

        if ((!count || count === 0) && !(await autoGeneratedRecently(admin, siteId))) {
          console.log(`Auto-generating first-time recommendations for site ${siteId}`)
          await generateRecommendations(siteId, { source: "auto" })
        }
      } catch (err) {
        console.error(`Auto rec-generation failed for site ${siteId}:`, err)
      }
    })

    return successResponse({ status: "syncing", siteId })
  } catch (e) {
    const message = e instanceof Error ? e.message : "Unknown error"
    if (message === "UNAUTHORIZED") return errors.unauthorized()
    return errors.internal("Failed to trigger sync")
  }
}
